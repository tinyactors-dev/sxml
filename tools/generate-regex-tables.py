#!/usr/bin/env python3
"""Generates src/regex_unicode.c, the character sets of the regex seed.

Usage: tools/generate-regex-tables.py UnicodeData.txt > src/regex_unicode.c

UnicodeData.txt is the Unicode Character Database file of the version named
in UNICODE_VERSION (https://www.unicode.org/Public/<version>/ucd/). The
output lists, as sorted codepoint ranges:
  - \\d: general category Nd (XSD 1.1 Part 2, appendix G "Regular
    Expressions", "Multi-character escapes": \\d = \\p{Nd});
  - \\w: every codepoint not in categories P, Z or C (\\w =
    [#x0000-#x10FFFF]-[\\p{P}\\p{Z}\\p{C}]); unassigned codepoints are Cn, so
    \\w holds only assigned codepoints of categories L, M, N and S.
"""
import hashlib
import sys

UNICODE_VERSION = "16.0.0"


def read_categories(path):
    """Yields (first, last, category) for every assigned codepoint range."""
    with open(path, encoding="utf-8") as data_file:
        pending_first = None
        for line in data_file:
            fields = line.rstrip("\n").split(";")
            codepoint = int(fields[0], 16)
            name = fields[1]
            category = fields[2]
            if name.endswith(", First>"):
                pending_first = codepoint
                continue
            if name.endswith(", Last>"):
                yield pending_first, codepoint, category
                pending_first = None
                continue
            yield codepoint, codepoint, category


def merge(ranges):
    merged = []
    for first, last in sorted(ranges):
        if merged and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last))
        else:
            merged.append((first, last))
    return merged


def emit_table(name, ranges):
    lines = [f"static const sxml_regex_codepoint_range {name}[] = {{"]
    for first, last in ranges:
        lines.append(f"    {{0x{first:04X}, 0x{last:04X}}},")
    lines.append("};")
    return "\n".join(lines)


def main():
    path = sys.argv[1]
    with open(path, "rb") as data_file:
        digest = hashlib.sha256(data_file.read()).hexdigest()
    digit_ranges = []
    word_ranges = []
    for first, last, category in read_categories(path):
        if category == "Nd":
            digit_ranges.append((first, last))
        if category[0] in "LMNS":
            word_ranges.append((first, last))
    digit_ranges = merge(digit_ranges)
    word_ranges = merge(word_ranges)
    print(f"""/*
 * Character sets of the regex seed (src/regex_internal.h), generated by
 * tools/generate-regex-tables.py from UnicodeData.txt of Unicode
 * {UNICODE_VERSION} (SHA-256 {digest[:32]}
 * {digest[32:]}). Do not edit; regenerate.
 *
 * XSD 1.1 Part 2, appendix G, "Multi-character escapes":
 * \\d is \\p{{Nd}}; \\w is [#x0000-#x10FFFF]-[\\p{{P}}\\p{{Z}}\\p{{C}}].
 */
#include "regex_internal.h"

/* clang-format off */
{emit_table("sxml_regex_decimal_digit_ranges", digit_ranges)}

{emit_table("sxml_regex_word_character_ranges", word_ranges)}
/* clang-format on */

/* Binary search for codepoint in sorted, disjoint ranges. */
static bool sxml_regex_ranges_contain(sxml_regex_codepoint_range_list list,
                                      uint32_t codepoint) {{
    size_t low_index = 0;
    size_t high_index = list.range_count;
    while (low_index < high_index) {{
        size_t middle_index = low_index + (high_index - low_index) / 2;
        const sxml_regex_codepoint_range *range = &list.ranges[middle_index];
        if (codepoint >= range->first_codepoint &&
            codepoint <= range->last_codepoint) {{
            return true;
        }}
        if (codepoint < range->first_codepoint) {{
            high_index = middle_index;
        }} else {{
            low_index = middle_index + 1;
        }}
    }}
    return false;
}}

bool sxml_regex_is_decimal_digit(uint32_t codepoint) {{
    return sxml_regex_ranges_contain(
        (sxml_regex_codepoint_range_list){{
            .ranges = sxml_regex_decimal_digit_ranges,
            .range_count = sizeof(sxml_regex_decimal_digit_ranges) /
                           sizeof(sxml_regex_decimal_digit_ranges[0]),
        }},
        codepoint);
}}

bool sxml_regex_is_word_character(uint32_t codepoint) {{
    return sxml_regex_ranges_contain(
        (sxml_regex_codepoint_range_list){{
            .ranges = sxml_regex_word_character_ranges,
            .range_count = sizeof(sxml_regex_word_character_ranges) /
                           sizeof(sxml_regex_word_character_ranges[0]),
        }},
        codepoint);
}}""")


if __name__ == "__main__":
    main()
