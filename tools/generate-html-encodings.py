#!/usr/bin/env python3
"""Generate src/html_encoding_tables.c: the encoding labels, the legacy
single-byte encodings and the indexes of the legacy multi-byte encodings of
the WHATWG Encoding Standard, which the HTML parser decodes octets with
(HTML Living Standard, 13.2.3; packets 7.10a and 7.10b).

Usage: tools/generate-html-encodings.py ENCODING-DIRECTORY > src/html_encoding_tables.c

ENCODING-DIRECTORY holds encodings.json and index-NAME.txt for every
legacy single-byte encoding and for jis0208, jis0212, euc-kr, gb18030,
gb18030-ranges and big5, from https://encoding.spec.whatwg.org/
(encodings.json, index-ibm866.txt ... index-x-mac-cyrillic.txt,
index-jis0208.txt ...).
"""
import hashlib
import json
import os
import sys

# Encodings the decoder treats itself, numbered as src/html_internal.h
# numbers them; the single-byte encodings follow in the standard's order.
SPECIAL_ENCODINGS = ["UTF-8", "UTF-16BE", "UTF-16LE", "replacement", "x-user-defined"]
SINGLE_BYTE_HEADING = "Legacy single-byte encodings"
# The multi-byte encodings, numbered after the single-byte ones as
# src/html_internal.h numbers them (SXML_HTML_ENCODING_GBK ...).
MULTI_BYTE_ENCODINGS = ["GBK", "gb18030", "Big5", "EUC-JP", "ISO-2022-JP", "Shift_JIS", "EUC-KR"]
MULTI_BYTE_MACROS = ["GBK", "GB18030", "BIG5", "EUC_JP", "ISO_2022_JP", "SHIFT_JIS", "EUC_KR"]
# The pointer-indexed tables: (index name, C name, first pointer).
INDEXES = [("jis0208", "jis0208", 0), ("jis0212", "jis0212", 0), ("euc-kr", "euc_kr", 0),
           ("gb18030", "gb18030", 0), ("big5", "big5", 942)]


def main():
    directory = sys.argv[1]
    encodings_path = os.path.join(directory, "encodings.json")
    with open(encodings_path, encoding="utf-8") as encodings_file:
        groups = json.load(encodings_file)
    single_byte = []
    numbers = {}
    for number, name in enumerate(SPECIAL_ENCODINGS):
        numbers[name] = number
    for group in groups:
        if group["heading"] == SINGLE_BYTE_HEADING:
            for encoding in group["encodings"]:
                numbers[encoding["name"]] = len(SPECIAL_ENCODINGS) + len(single_byte)
                single_byte.append(encoding["name"])
    first_multi_byte = len(SPECIAL_ENCODINGS) + len(single_byte)
    for offset, name in enumerate(MULTI_BYTE_ENCODINGS):
        numbers[name] = first_multi_byte + offset
    labels = []
    for group in groups:
        for encoding in group["encodings"]:
            number = numbers[encoding["name"]]
            for label in encoding["labels"]:
                labels.append((label.encode("ascii"), number, encoding["name"]))
    labels.sort()
    digests = [("encodings.json", hashlib.sha256(open(encodings_path, "rb").read()).hexdigest())]
    tables = []
    for name in single_byte:
        # ISO-8859-8-I decodes as ISO-8859-8 (Encoding Standard, 9.1).
        index_name = "iso-8859-8" if name == "ISO-8859-8-I" else name.lower()
        path = os.path.join(directory, "index-%s.txt" % index_name)
        if name == "ISO-8859-8-I":
            tables.append((name, tables[-1][1]))
            continue
        digests.append((os.path.basename(path), hashlib.sha256(open(path, "rb").read()).hexdigest()))
        codepoints = [0] * 128
        with open(path, encoding="utf-8") as index_file:
            for line in index_file:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                pointer, codepoint = line.split("\t")[:2]
                codepoints[int(pointer)] = int(codepoint, 16)
        tables.append((name, codepoints))
    indexes = []
    big5_plane_2 = []
    for index_name, c_name, first_pointer in INDEXES:
        path = os.path.join(directory, "index-%s.txt" % index_name)
        digests.append((os.path.basename(path), hashlib.sha256(open(path, "rb").read()).hexdigest()))
        entries = read_index(path)
        last_pointer = max(entries)
        codepoints = [0] * (last_pointer + 1 - first_pointer)
        for pointer, codepoint in entries.items():
            if codepoint > 0xFFFF:
                # Only Big5 has code points above U+FFFF, all in plane 2.
                assert index_name == "big5" and codepoint >> 16 == 2
                big5_plane_2.append(pointer)
            codepoints[pointer - first_pointer] = codepoint & 0xFFFF
        indexes.append((index_name, c_name, first_pointer, codepoints))
    big5_plane_2.sort()
    ranges_path = os.path.join(directory, "index-gb18030-ranges.txt")
    digests.append((os.path.basename(ranges_path),
                    hashlib.sha256(open(ranges_path, "rb").read()).hexdigest()))
    ranges = sorted(read_index(ranges_path).items())

    out = sys.stdout
    out.write("/*\n * Generated by tools/generate-html-encodings.py from the WHATWG Encoding\n")
    out.write(" * Standard; do not edit. The encoding labels and the legacy single-byte\n")
    out.write(" * encodings the HTML parser decodes with (src/html_internal.h).\n *\n")
    for file_name, digest in digests:
        out.write(" * %s sha256 %s\n" % (file_name, digest))
    out.write(" */\n")
    out.write('#include "html_internal.h"\n\n')
    out.write("const sxml_html_encoding_label sxml_html_encoding_labels[] = {\n")
    for label, number, name in labels:
        out.write('    {SXML_BYTE_VIEW_INITIALIZER("%s"), %d}, /* %s */\n'
                  % (label.decode("ascii"), number, name))
    out.write("};\n")
    out.write("const size_t sxml_html_encoding_label_count =\n"
              "    sizeof(sxml_html_encoding_labels) / sizeof(sxml_html_encoding_labels[0]);\n\n")
    out.write("const uint16_t sxml_html_single_byte_codepoints[][128] = {\n")
    for name, codepoints in tables:
        out.write("    /* %s */\n    {\n" % name)
        for row in range(0, 128, 8):
            out.write("        " + ", ".join("0x%04X" % codepoint
                                            for codepoint in codepoints[row:row + 8]) + ",\n")
        out.write("    },\n")
    out.write("};\n")
    out.write("const size_t sxml_html_single_byte_encoding_count = %d;\n" % len(tables))
    out.write("_Static_assert(SXML_HTML_ENCODING_WINDOWS_1252 == %d, \"the generator's numbering\");\n"
              % numbers["windows-1252"])
    for offset, macro in enumerate(MULTI_BYTE_MACROS):
        out.write("_Static_assert(SXML_HTML_ENCODING_%s == %d, \"the generator's numbering\");\n"
                  % (macro, first_multi_byte + offset))
    for index_name, c_name, first_pointer, codepoints in indexes:
        out.write("\n/* index %s, pointers %d to %d; 0 where a pointer has no code point. */\n"
                  % (index_name, first_pointer, first_pointer + len(codepoints) - 1))
        out.write("const uint16_t sxml_html_index_%s[%d] = {\n" % (c_name, len(codepoints)))
        write_numbers(out, ["0x%04X" % codepoint for codepoint in codepoints])
        out.write("};\n")
    out.write("\n/* The Big5 pointers whose code points are in plane 2: U+20000 plus the\n"
              "   index's value. Sorted. */\n")
    out.write("const uint16_t sxml_html_big5_plane_2_pointers[%d] = {\n" % len(big5_plane_2))
    write_numbers(out, ["%d" % pointer for pointer in big5_plane_2])
    out.write("};\n")
    out.write("\n/* index gb18030 ranges: pointers and their code points. */\n")
    out.write("const uint32_t sxml_html_gb18030_range_pointers[%d] = {\n" % len(ranges))
    write_numbers(out, ["%d" % pointer for pointer, _ in ranges])
    out.write("};\n")
    out.write("const uint32_t sxml_html_gb18030_range_codepoints[%d] = {\n" % len(ranges))
    write_numbers(out, ["0x%04X" % codepoint for _, codepoint in ranges])
    out.write("};\n")


def read_index(path):
    entries = {}
    with open(path, encoding="utf-8") as index_file:
        for line in index_file:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            pointer, codepoint = line.split("\t")[:2]
            entries[int(pointer)] = int(codepoint, 16)
    return entries


def write_numbers(out, numbers):
    for row in range(0, len(numbers), 10):
        out.write("    " + ", ".join(numbers[row:row + 10]) + ",\n")


if __name__ == "__main__":
    main()
