#!/usr/bin/env python3
"""Generates src/source_code_languages.c, the languages of sxml:parse-code.

Usage: tools/generate-source-code-languages.py > src/source_code_languages.c

Reads every grammar vendored under third_party/tree-sitter-grammars
(tools/vendor-tree-sitter-grammar.sh; packet 7.22, D285) and writes one
table row per language, in name order: its name (the directory's), the
entry point of its parser (tree_sitter_NAME, renamed
sxml_source_language_NAME by cmake/SxmlGrammar.cmake), its highlights,
locals and injections queries (the files its VERSION names under
"Highlights:", "Locals:" and "Injections:", each kind's files in that
order, concatenated; packet 7.23, D288) and its injection regex
("Injection-regex:"). Comment lines and blank lines of the queries are
dropped; the rest is kept byte for byte, so ts_query_new reads the
patterns the grammar's authors wrote, in their order (the last pattern
that captures a node gives its highlight, D285).
"""
import os
import sys

REPOSITORY_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GRAMMARS = os.path.join(REPOSITORY_ROOT, "third_party", "tree-sitter-grammars")


def version_field(language_directory, field):
    """The words of the VERSION line "FIELD:", or None without one."""
    with open(os.path.join(language_directory, "VERSION"), encoding="utf-8") as version:
        for line in version:
            if line.startswith(field + ":"):
                return line[len(field) + 1:].split()
    return None


def query_files(language_directory, kind):
    files = version_field(language_directory, kind)
    if files is None and kind == "Highlights":
        raise SystemExit(f"{language_directory}/VERSION names no highlights queries")
    return files or []


def query_text(language_directory, kind):
    lines = []
    for name in query_files(language_directory, kind):
        with open(os.path.join(language_directory, name), encoding="utf-8") as query:
            for line in query:
                stripped = line.strip()
                if stripped == "" or stripped.startswith(";"):
                    continue
                lines.append(line.rstrip("\n").rstrip())
    return "\n".join(lines) + "\n" if lines else ""


def c_escape(line):
    return (line.replace("\\", "\\\\").replace('"', '\\"')
            .replace("\t", "\\t").replace("?", "\\?"))


def c_literal_lines(text):
    """The text as C string literals, one per line of it."""
    if text == "":
        yield '    ""'
    for line in text.split("\n")[:-1]:
        yield f'    "{c_escape(line)}\\n"'


QUERY_KINDS = (("Highlights", "highlights"), ("Locals", "locals"), ("Injections", "injections"))


def main():
    languages = sorted(
        name for name in os.listdir(GRAMMARS)
        if os.path.isfile(os.path.join(GRAMMARS, name, "src", "parser.c")))
    output = sys.stdout
    output.write("""/*
 * The built-in languages of sxml:parse-code (src/source_code_internal.h;
 * packets 7.22 and 7.23, D285, D288): one row per tree-sitter grammar
 * vendored under third_party/tree-sitter-grammars, with its highlights,
 * locals and injections queries and its injection regex.
 * Generated by tools/generate-source-code-languages.py; do not edit.
 */
#include "source_code_internal.h"

""")
    for language in languages:
        output.write(f"/* Defined by third_party/tree-sitter-grammars/{language}/src/parser.c. */\n")
        output.write("const TSLanguage *\n")
        output.write(f"sxml_source_language_{language}(void); // NOLINT(readability-identifier-naming)\n\n")
    for language in languages:
        directory = os.path.join(GRAMMARS, language)
        for field, kind in QUERY_KINDS:
            files = query_files(directory, field)
            output.write(f"/* {language} {kind}: {' '.join(files) if files else 'none'} */\n")
            output.write(f"static const char {language}_{kind}_query[] =\n")
            output.write("\n".join(c_literal_lines(query_text(directory, field))))
            output.write(";\n\n")
    output.write("static const sxml_source_code_builtin_language builtin_languages[] = {\n")
    for language in languages:
        regex = " ".join(version_field(os.path.join(GRAMMARS, language), "Injection-regex") or [])
        output.write(f"""    {{.language_name = SXML_BYTE_VIEW_INITIALIZER("{language}"),
     .get_grammar = sxml_source_language_{language},
     .highlights_query = SXML_BYTE_VIEW_INITIALIZER({language}_highlights_query),
     .locals_query = SXML_BYTE_VIEW_INITIALIZER({language}_locals_query),
     .injections_query = SXML_BYTE_VIEW_INITIALIZER({language}_injections_query),
     .injection_regex = SXML_BYTE_VIEW_INITIALIZER("{c_escape(regex)}")}},
""")
    output.write("""};

const sxml_source_code_builtin_language_view sxml_source_code_builtin_languages = {
    .languages = builtin_languages,
    .language_count = sizeof(builtin_languages) / sizeof(builtin_languages[0]),
};
""")


if __name__ == "__main__":
    main()
