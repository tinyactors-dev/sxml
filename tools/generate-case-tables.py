#!/usr/bin/env python3
"""Generates src/function_library_case.c, the case mappings of fn:upper-case
and fn:lower-case.

Usage: tools/generate-case-tables.py UnicodeData.txt SpecialCasing.txt \\
           > src/function_library_case.c

Both files are from the Unicode Character Database of the version named in
UNICODE_VERSION (https://www.unicode.org/Public/<version>/ucd/). F&O 4.0,
fn:upper-case and fn:lower-case, use the Unicode case mappings: the simple
mappings of UnicodeData.txt (fields 12 and 13), replaced by the full
mappings of SpecialCasing.txt where those have no condition (the
language-sensitive and context-sensitive ones are not used).

The output holds, per direction, sorted runs (first, last, delta, stride):
every codepoint first + k * stride up to last maps to itself plus delta;
and a sorted list of the full mappings to two or three codepoints.
"""
import hashlib
import sys

UNICODE_VERSION = "16.0.0"


def read_simple(path):
    upper = {}
    lower = {}
    with open(path, encoding="utf-8") as data_file:
        for line in data_file:
            fields = line.rstrip("\n").split(";")
            codepoint = int(fields[0], 16)
            if fields[12]:
                upper[codepoint] = [int(fields[12], 16)]
            if fields[13]:
                lower[codepoint] = [int(fields[13], 16)]
    return upper, lower


def read_special(path, upper, lower):
    with open(path, encoding="utf-8") as data_file:
        for line in data_file:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            fields = [field.strip() for field in line.split(";")]
            # code; lower; title; upper; (condition_list;)?
            if len(fields) > 4 and fields[4]:
                continue
            codepoint = int(fields[0], 16)
            lower_mapping = [int(part, 16) for part in fields[1].split()]
            upper_mapping = [int(part, 16) for part in fields[3].split()]
            for table, mapping in ((lower, lower_mapping), (upper, upper_mapping)):
                if mapping == [codepoint]:
                    table.pop(codepoint, None)
                else:
                    table[codepoint] = mapping


def runs_of(table):
    """Single-codepoint mappings as (first, last, delta, stride) runs."""
    singles = sorted((codepoint, mapping[0] - codepoint)
                     for codepoint, mapping in table.items() if len(mapping) == 1)
    runs = []
    for codepoint, delta in singles:
        if runs:
            first, last, run_delta, stride = runs[-1]
            if run_delta == delta:
                if first == last and codepoint - last in (1, 2):
                    runs[-1] = (first, codepoint, delta, codepoint - last)
                    continue
                if codepoint - last == stride:
                    runs[-1] = (first, codepoint, delta, stride)
                    continue
        runs.append((codepoint, codepoint, delta, 1))
    return runs


def emit_runs(name, runs):
    lines = [f"static const case_run {name}[] = {{"]
    for first, last, delta, stride in runs:
        lines.append(f"    {{0x{first:05X}, 0x{last:05X}, {delta}, {stride}}},")
    lines.append("};")
    return "\n".join(lines)


def emit_full(name, table):
    lines = [f"static const case_full_mapping {name}[] = {{"]
    for codepoint in sorted(table):
        mapping = table[codepoint]
        if len(mapping) == 1:
            continue
        padded = mapping + [0] * (3 - len(mapping))
        parts = ", ".join(f"0x{part:05X}" for part in padded)
        lines.append(f"    {{0x{codepoint:05X}, {{{parts}}}, {len(mapping)}}},")
    lines.append("};")
    return "\n".join(lines)


def digest_of(path):
    with open(path, "rb") as data_file:
        return hashlib.sha256(data_file.read()).hexdigest()


def main():
    data_path, special_path = sys.argv[1], sys.argv[2]
    upper, lower = read_simple(data_path)
    read_special(special_path, upper, lower)
    data_digest = digest_of(data_path)
    special_digest = digest_of(special_path)
    print(f"""/*
 * Case mappings of fn:upper-case and fn:lower-case
 * (src/function_library_core_internal.h), generated by
 * tools/generate-case-tables.py from Unicode {UNICODE_VERSION}:
 * UnicodeData.txt (SHA-256 {data_digest[:32]}
 * {data_digest[32:]}) and SpecialCasing.txt (SHA-256
 * {special_digest[:32]}
 * {special_digest[32:]}). Do not edit; regenerate.
 *
 * F&O 4.0, fn:upper-case and fn:lower-case: the Unicode full case
 * mappings without the language-sensitive and conditional ones.
 */
#include "function_library_core_internal.h"

/* Codepoints first, first + stride, ... up to last map to codepoint +
   delta. */
typedef struct case_run {{
    uint32_t first_codepoint;
    uint32_t last_codepoint;
    int32_t delta;
    uint32_t stride;
}} case_run;

/* A codepoint that maps to two or three codepoints. */
typedef struct case_full_mapping {{
    uint32_t codepoint;
    uint32_t mapped_codepoints[3];
    uint32_t mapped_codepoint_count;
}} case_full_mapping;

typedef struct case_run_list {{
    const case_run *runs;
    size_t run_count;
}} case_run_list;

typedef struct case_full_mapping_list {{
    const case_full_mapping *full_mappings;
    size_t full_mapping_count;
}} case_full_mapping_list;

/* clang-format off */
{emit_runs("upper_case_runs", runs_of(upper))}

{emit_runs("lower_case_runs", runs_of(lower))}

{emit_full("upper_case_full_mappings", upper)}

{emit_full("lower_case_full_mappings", lower)}
/* clang-format on */

/* The full mapping of codepoint, or NULL. */
static const case_full_mapping *find_full_mapping(case_full_mapping_list list,
                                                  uint32_t codepoint) {{
    size_t low_index = 0;
    size_t high_index = list.full_mapping_count;
    while (low_index < high_index) {{
        const size_t middle_index = low_index + (high_index - low_index) / 2;
        const case_full_mapping *mapping = &list.full_mappings[middle_index];
        if (mapping->codepoint == codepoint) {{
            return mapping;
        }}
        if (codepoint < mapping->codepoint) {{
            high_index = middle_index;
        }} else {{
            low_index = middle_index + 1;
        }}
    }}
    return NULL;
}}

/* The codepoint codepoint maps to through the runs (itself when none). */
static uint32_t map_through_runs(case_run_list list, uint32_t codepoint) {{
    size_t low_index = 0;
    size_t high_index = list.run_count;
    while (low_index < high_index) {{
        const size_t middle_index = low_index + (high_index - low_index) / 2;
        const case_run *run = &list.runs[middle_index];
        if (codepoint < run->first_codepoint) {{
            high_index = middle_index;
        }} else if (codepoint > run->last_codepoint) {{
            low_index = middle_index + 1;
        }} else {{
            if ((codepoint - run->first_codepoint) % run->stride != 0) {{
                return codepoint;
            }}
            return (uint32_t)((int64_t)codepoint + run->delta);
        }}
    }}
    return codepoint;
}}

void sxml_function_library_map_case(sxml_case_mapping_request request,
                                    sxml_case_mapping *mapping) {{
    const bool is_upper = request.mapping_kind == SXML_CASE_MAPPING_KIND_UPPER;
    const case_full_mapping_list full_list = {{
        .full_mappings = is_upper ? upper_case_full_mappings : lower_case_full_mappings,
        .full_mapping_count =
            is_upper ? sizeof(upper_case_full_mappings) / sizeof(upper_case_full_mappings[0])
                     : sizeof(lower_case_full_mappings) / sizeof(lower_case_full_mappings[0]),
    }};
    const case_full_mapping *full = find_full_mapping(full_list, request.codepoint);
    if (full != NULL) {{
        *mapping = (sxml_case_mapping){{
            .codepoints = {{full->mapped_codepoints[0], full->mapped_codepoints[1],
                           full->mapped_codepoints[2]}},
            .codepoint_count = full->mapped_codepoint_count}};
        return;
    }}
    const case_run_list run_list = {{
        .runs = is_upper ? upper_case_runs : lower_case_runs,
        .run_count = is_upper ? sizeof(upper_case_runs) / sizeof(upper_case_runs[0])
                              : sizeof(lower_case_runs) / sizeof(lower_case_runs[0]),
    }};
    *mapping = (sxml_case_mapping){{
        .codepoints = {{map_through_runs(run_list, request.codepoint), 0, 0}},
        .codepoint_count = 1}};
}}""")


if __name__ == "__main__":
    main()
