#pragma once

/*
 * Invisible XML (Invisible XML Specification 1.0, with the errata of the
 * Community Group's editorial draft of 2026-02-03; F&O 4.0,
 * fn:invisible-xml; packet 7.18, D215). Internal to sxml; an optional
 * feature (D189): only a program that names sxml_invisible_xml_feature()
 * links it.
 *
 * One mechanism serves grammars and inputs alike:
 * - src/ixml.c: the grammar builder, which reads a grammar in its XML form
 *   (the Specification, "IXML in XML") as tree builder events or as
 *   entries of a constant table, and compiles it into an `ixml_grammar`
 *   (glossary); the serializer, which turns a parse tree into tree builder
 *   events with the marks, aliases and insertions applied ("Constructing
 *   XML"); the failure document; and the feature.
 * - src/ixml_tables.c: what the parser reads of a compiled grammar,
 *   computed once when it is compiled: `dotted_rule`s, `distinct_terminal`s,
 *   the `codepoint_class`es of ASCII, and the `lookahead_set` of every
 *   dotted rule (FIRST and FOLLOW sets; glossary, D283).
 * - src/ixml_tokens.c: the `regular_token`s of a compiled grammar and
 *   their `token_automaton`s (glossary, D290), computed once when it is
 *   compiled.
 * - src/ixml_earley.c: the Earley parser, with one character of lookahead,
 *   `leo_item`s (D283) and regular tokens read in one step (D290). Its
 *   items, with the first way each was derived and whether there was a
 *   second, are the `parse_forest` (glossary); the parse tree is read out
 *   of them.
 * - src/ixml_grammar_table.c: the grammar of iXML grammars as a constant
 *   table of its XML form (generated by tools/generate-ixml-grammar.py).
 *   A grammar in ixml notation is parsed with it, and the parse is
 *   serialized into the grammar builder, so there is one compiler.
 * - src/function_library_ixml.c: fn:invisible-xml, the feature's library
 *   function (D191), and the parser function it returns.
 *
 * No recursion (D71): the compiler works through a list of pending
 * nonterminals, the parser through its item sets, and the tree walks
 * follow parent links.
 *
 * Thread safety: the thread of the caller. A compiled grammar is never
 * written after it is compiled, so parses may share it.
 */
